import request from './request'
import { DEMO_MONTH } from './mock/period'

/**
 * 余量查询。《开发文档》§6.4 #1（账户总览）与 #4（余量查询）共用这一个函数。
 *
 * ---------------------------------------------------------------------------
 * **减法在后端做，不在这里做。** 这是本文件最要紧的一条约定。
 *
 * 余量 = 套餐额度 − 本月已用，看着只有一行减法，但它牵着一个真实的坑：
 * `data_quota` 与 `used_data` 必须同单位（GB 对 GB）。单位若不一致——
 * 比如一侧是 GB、一侧是 MB——相减**不报错、不抛异常，结果只是错**，
 * 错成一个看起来很正常的数字（页面显示「剩余 59.8GB」而实际应为「47.3GB」）。
 * 这类错误不崩不炸，验收前几乎发现不了。
 *
 * 假数据阶段这条减法在本文件里做过；接线后它回到了 `AccountService`
 * ——那里的 `quota / used / remain` 三个数一起给，前端只负责显示。
 * **别把这条减法挪回前端**，哪怕只是「顺手算一下百分比」：`percent` 也由后端给，
 * 它要在超套时封顶 100%，`remain` 却要照实为负——这两条规则只有一份。
 * ---------------------------------------------------------------------------
 */
export function getRemaining(month = DEMO_MONTH) {
  // ⚠️ month 默认取演示账期：种子数据围绕 2026-09 构造（见 `mock/period.js`）。
  //    服务端在不传 month 时按当前时间算账期；演示期结束后删掉这个默认值。
  return request.get('/account/usage/remaining', { params: { month } })
}
